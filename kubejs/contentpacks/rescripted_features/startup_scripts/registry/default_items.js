/**
* @param {Registry.Item} event
*/
function item_registery_default_items(event) {
	let register_general = (id,display_name,model) => {
		event.create(id)
		.texture('layer0', `kubejs:item/${model}`)
		.displayName(display_name)
	}
	//basic items
	register_general("cut_carpet","Cut Carpet","cut_carpet")
	register_general("scrap","Scrap","scrap")
	register_general("putty_knife","Putty Knife","tools/putty_knife")
	register_general("carpet_dust","Carpet Dust","carpet_dust")
	register_general("moderate_soul_gem","Moderate Soul Gem","moderate_soul_gem")
	register_general("concrete_piece","Piece of Concrete","concrete_piece")
	register_general("party_popper","Party Popper","tools/party_popper")
	register_general("battery","Battery","battery")
	register_general("soul_fuse","Soul Fuse","soul_fuse")
	register_general("empty_fuse","Empty Fuse","empty_fuse")
	register_general("error_item","Error","error_item")
	register_general("wallpaper","Wallpaper","wallpaper")
	register_general("fluorescent_tube","Fluorescent Tube","fluorescent_tube")
	register_general("sentimental_thaumium","Sentimental Thaumium","sentimental_thaumium")
	register_general("overclocked_clock","Overclocked Clock","overclocked_clock")
	register_general("ai","Artificial Intelligence","ai")
	register_general("quantum_string","Quantum String","quantum_string")
	register_general("cobblestone_bucket","Bucket of Cobblestone","cobblestone_bucket")
	register_general("drain_item","Drain Grate","drain_item")
	register_general("makeshift_lodestone_chunk","Makeshift Lodestone Chunk","lodestone_chunk")
	register_general("uv_fluorescent_tube","UV Fluorescent Tube","uv_fluorescent_tube")

	//tools
	let w_knife = event.create('wooden_knife', 'sword')
	w_knife.texture('layer0', 'kubejs:item/tools/wooden_knife')
	w_knife.unstackable()
	w_knife.maxDamage(16)
	w_knife.attackDamageBaseline(1)
	w_knife.tag("forge:tools/knives")
	w_knife.tag("farmersdelight:straw_harvesterss")
	w_knife.tag("farmersdelight:tools/knives")
	w_knife.displayName('Wooden Knife')
	let d_brush = event.create('diamond_brush', "basic")
	d_brush.texture('layer0', 'kubejs:item/tools/diamond_brush')
	d_brush.unstackable()
	d_brush.maxDamage(2048)
	d_brush.displayName('Diamond Brush')
	let b_knife = event.create('infinity_knife', 'sword')
	b_knife.texture('layer0', 'kubejs:item/tools/bedrock_knife')
	b_knife.unstackable()
	b_knife.attackDamageBaseline(9)
	b_knife.tag("forge:tools/knives")
	b_knife.maxDamage(4096)
	b_knife.tag("farmersdelight:straw_harvesterss")
	b_knife.tag("farmersdelight:tools/knives")
	b_knife.displayName('Infinity Knife')

	let crowbar = event.create('crowbar', "basic")
	crowbar.texture('layer0', 'kubejs:item/tools/crowbar')
	crowbar.tag("kubejs:crowbars")
	crowbar.displayName('Crowbar')
	let dark_steel_crowbar = event.create('dark_steel_crowbar', "basic")
	dark_steel_crowbar.texture('layer0', 'kubejs:item/tools/dark_steel_crowbar')
	dark_steel_crowbar.tag("kubejs:crowbars")
	dark_steel_crowbar.displayName('Dark Steel Crowbar')

	let power_box = event.create("power_box")
	power_box.displayName("Power Box")
}