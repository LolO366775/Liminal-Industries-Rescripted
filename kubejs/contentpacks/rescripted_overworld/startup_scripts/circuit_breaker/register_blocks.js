StartupEvents.registry('block', event => {
	let controller = event.create('controller_wallpaper','cardinal')
	controller.model('kubejs:block/controller_wallpaper/default')
	controller.fullBlock(true)
	controller.material("wood")
	controller.soundType("cherry_wood")
    controller.unbreakable()
	controller.tagBlock('wither_immune')
	controller.blockEntity(entityInfo => { entityInfo.serverTick(20, 0, entity => {
		global.tick_controller_wallpaper(entity, false)
	})})
	controller.displayName('Embedded Power Box')

	let exposed = event.create('exposed_controller_wallpaper','cardinal')
	exposed.model('kubejs:block/controller_wallpaper/exposed')
	exposed.fullBlock(true)
	exposed.material("wood")
	exposed.soundType("cherry_wood")
    exposed.unbreakable()
	exposed.defaultCutout()
	exposed.transparent(true)
	exposed.tagBlock('wither_immune')
	exposed.displayName('Harvested Power Box (Wires)')

	let harvested = event.create('controller_wallpaper_dead','cardinal')
	harvested.model('kubejs:block/controller_wallpaper/dead')
	harvested.fullBlock(true)
	harvested.material("wood")
	harvested.soundType("cherry_wood")
    harvested.unbreakable()
	harvested.defaultCutout()
	harvested.transparent(true)
	harvested.tagBlock('wither_immune')
	harvested.randomTick(tick => {
		global.tick_harvested_controller_wallpaper(entity)
	})
	harvested.displayName('Harvested Power Box (Empty)')

	let generator = event.create('backup_generator','cardinal')
	generator.model('kubejs:block/controller_wallpaper/generator')
	generator.fullBlock(true)
	generator.material("wood")
	generator.soundType("cherry_wood")
	generator.unbreakable()
	generator.tagBlock('wither_immune')
	generator.blockEntity(entityInfo => { entityInfo.serverTick(20, 0, entity => {
		global.tick_controller_wallpaper(entity, true)
	})})
	generator.displayName('Backup Generator')
})